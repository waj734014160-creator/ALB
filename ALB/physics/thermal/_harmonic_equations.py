"""Analytic pressure, energy, and restrictor blocks for local ALB harmonics.

Migrated from the verified July 2026 equation implementation; provenance and
frozen pre-migration arrays are in refs/thermal_harmonic_migration_v1.json.
SUPG tau and thermal boundary/source branches are frozen at the initial steady
state. Cavitation is solved only for the base and fixed for all tangent solves.
"""

from __future__ import annotations

import numpy as np
import scipy.sparse as sp
from skfem import BilinearForm, LinearForm, asm
from skfem.helpers import grad

from ALB.contracts import BearingInput, UnitSystem
from ALB.physics.hydraulics.orifice import _attachment_matrix
from .solver import _build_film_grid, _reynolds_lhs_miu, _reynolds_rhs_miu0

@BilinearForm
def pressure_miu_block(u, v, w):
    """Map a nodal viscosity-ratio variation to the Reynolds residual."""

    pressure_gradient = grad(w.pressure0)
    return w.coeff * u * (
        w.lr**2 * pressure_gradient[0] * grad(v)[0]
        + pressure_gradient[1] * grad(v)[1]
    )


@LinearForm
def pressure_geometry_column(v, w):
    """Return the Reynolds residual column generated by dh and dh/dtau."""

    pressure_gradient = grad(w.pressure0)
    poiseuille = w.da_dh * w.dh * (
        w.lr**2 * pressure_gradient[0] * grad(v)[0]
        + pressure_gradient[1] * grad(v)[1]
    )
    wedge = w.lambda0 * grad(w.dh)[0] * v
    squeeze = 2.0 * w.lambda0 * w.vf * w.dh_dt * v
    return poiseuille + wedge + squeeze


@BilinearForm
def thermal_direct_block(u, v, w):
    """Direct temperature block with coefficients frozen at the base state."""

    grad_u = grad(u)
    grad_v = grad(v)
    q_grad_u = w.qx * grad_u[0] + w.qz * grad_u[1]
    q_grad_v = w.qx * grad_v[0] + w.qz * grad_v[1]
    return (
        w.diff_x * grad_u[0] * grad_v[0]
        + w.diff_z * grad_u[1] * grad_v[1]
        + q_grad_u * v
        + w.tau * q_grad_v * q_grad_u
    )


@LinearForm
def thermal_source_vector(v, w):
    """Thermal dissipation load including the frozen-tau SUPG load."""

    q_grad_v = w.qx * grad(v)[0] + w.qz * grad(v)[1]
    return w.phi * v + w.tau * q_grad_v * w.phi


@BilinearForm
def thermal_qx_coefficient_block(u, v, w):
    """Map a nodal qx coefficient variation to the energy residual."""

    grad_t = grad(w.temperature0)
    grad_v = grad(v)
    q_grad_t = w.qx * grad_t[0] + w.qz * grad_t[1]
    q_grad_v = w.qx * grad_v[0] + w.qz * grad_v[1]
    galerkin = u * grad_t[0] * v
    supg = w.tau * (
        u * grad_v[0] * (q_grad_t - w.phi)
        + q_grad_v * u * grad_t[0]
    )
    return galerkin + supg


@BilinearForm
def thermal_qz_coefficient_block(u, v, w):
    """Map a nodal qz coefficient variation to the energy residual."""

    grad_t = grad(w.temperature0)
    grad_v = grad(v)
    q_grad_t = w.qx * grad_t[0] + w.qz * grad_t[1]
    q_grad_v = w.qx * grad_v[0] + w.qz * grad_v[1]
    galerkin = u * grad_t[1] * v
    supg = w.tau * (
        u * grad_v[1] * (q_grad_t - w.phi)
        + q_grad_v * u * grad_t[1]
    )
    return galerkin + supg


@BilinearForm
def thermal_phi_coefficient_block(u, v, w):
    """Map a nodal dissipation-source variation to the energy residual."""

    q_grad_v = w.qx * grad(v)[0] + w.qz * grad(v)[1]
    return -u * v - w.tau * q_grad_v * u


@BilinearForm
def thermal_diff_x_coefficient_block(u, v, w):
    """Map a nodal circumferential diffusion variation to the residual."""

    return u * grad(w.temperature0)[0] * grad(v)[0]


@BilinearForm
def thermal_diff_z_coefficient_block(u, v, w):
    """Map a nodal axial diffusion variation to the residual."""

    return u * grad(w.temperature0)[1] * grad(v)[1]


def axis_derivative_entries(axis: np.ndarray, index: int):
    """Return exact first-derivative stencil entries for one grid row."""

    count = len(axis)
    if index == 0:
        spacing = float(axis[1] - axis[0])
        return ((0, -1.0 / spacing), (1, 1.0 / spacing))
    if index == count - 1:
        spacing = float(axis[-1] - axis[-2])
        return ((count - 2, -1.0 / spacing), (count - 1, 1.0 / spacing))
    left = float(axis[index] - axis[index - 1])
    right = float(axis[index + 1] - axis[index])
    return (
        (index - 1, -right / (left * (left + right))),
        (index, (right - left) / (left * right)),
        (index + 1, left / (right * (left + right))),
    )


class AnalyticPadSystem:
    """Fully analytic coupled equation and tangent system for one ALB pad."""

    def __init__(self, pad, base_result, base_input, spool_index):
        self.pad = pad
        self.wrapper = pad
        self.bearing = pad.bearing
        self.model = self.bearing.main_model
        self.thermal_model = pad.thermal_model
        self.orifice = self.bearing.simple_models[0]
        self.base_input = np.asarray(base_input, dtype=float).copy()
        self.spool_index = int(spool_index)
        self.n = len(self.model.nodes)
        self.of_nodes = np.asarray(
            [node.number for node in self.orifice.node], dtype=int
        )
        self.pressure_projection = _attachment_matrix(self.orifice.node, self.n)

        pressure = np.asarray(
            [node.p for node in self.model.nodes.values()], dtype=float
        )
        activity_threshold = max(1.0e-11, float(np.max(pressure)) * 1.0e-7)
        self.active_pressure = pressure > activity_threshold
        pressure[~self.active_pressure] = 0.0
        temperature = np.asarray(base_result["temperature_nondim"], dtype=float)
        orifice_state = np.r_[
            float(self.orifice.q),
            float(self.orifice.psv),
            np.asarray(self.orifice.qn, dtype=float),
        ]
        self.z = np.r_[pressure, temperature, orifice_state]

        self.grid = _build_film_grid(self.model)
        self.mesh_data = self.thermal_model.build_mesh(self.model, self.grid)
        self.mesh = self.mesh_data["mesh"]
        self.pressure_basis = self.model.basis
        self.thermal_basis = self.mesh_data["basis"]
        self.scales = self.mesh_data["scales"]
        self.film_to_thermal = np.asarray(
            self.mesh_data["film_to_thermal_idx"], dtype=int
        )
        self.thermal_to_film = np.asarray(
            self.mesh_data["thermal_to_film_idx"], dtype=int
        )
        self.map_film_from_thermal = sp.csr_matrix(
            (
                np.ones(self.n),
                (np.arange(self.n), self.film_to_thermal),
            ),
            shape=(self.n, self.n),
        )
        self.map_thermal_from_film = sp.csr_matrix(
            (
                np.ones(self.n),
                (np.arange(self.n), self.thermal_to_film),
            ),
            shape=(self.n, self.n),
        )
        self.gradient_theta, self.gradient_zeta = self._build_gradient_operators()
        self.force_operator = self._build_force_operator()

        self._set_fields(self.z, self.base_input)
        initial_context = self._thermal_context(self.z)
        self.tau = (
            self.thermal_model._calc_nondim_supg_tau_nodal(
                self.mesh,
                initial_context["diff_x"],
                initial_context["diff_z"],
                initial_context["qx"],
                initial_context["qz"],
            )
            if self.wrapper.config.supg
            else np.zeros(self.n, dtype=float)
        )
        self.dirichlet_nodes, self.temperature_bc = self._thermal_boundary(
            initial_context["qz"]
        )
        self.cold_source_active = self.z[2 * self.n + 2 :] > 0.0
        self.cold_source_nodes = self._cold_source_nodes()
        points = np.asarray([
            item["position_nondim"]
            for item in self.orifice.flow_info(self.model)["flow_params"]
        ], dtype=float)
        if self.orifice.flow_projection == "element_shape":
            self.thermal_projection = self.thermal_basis.probes(points.T).tocsr()
        else:
            self.thermal_projection = sp.csr_matrix(
                (np.ones(3), (np.arange(3), self.cold_source_nodes)),
                shape=(3, self.n),
            )
        self.last_context = None

    @property
    def state_size(self):
        """Return the coupled state size."""

        return 2 * self.n + 5

    def _split(self, z):
        """Split pressure, temperature, and orifice unknowns."""

        return (
            np.asarray(z[: self.n], dtype=float),
            np.asarray(z[self.n : 2 * self.n], dtype=float),
            np.asarray(z[2 * self.n :], dtype=float),
        )

    def _build_gradient_operators(self):
        """Build the exact linear nodal gradient operators used by the solver."""

        nx = len(self.grid["x_axis"])
        nz = len(self.grid["z_axis"])
        grid_to_film = np.full((nx, nz), -1, dtype=int)
        grid_to_film[self.grid["ix"], self.grid["iz"]] = np.arange(self.n)
        rows_theta = []
        cols_theta = []
        data_theta = []
        rows_zeta = []
        cols_zeta = []
        data_zeta = []
        for row, (ix, iz) in enumerate(
            zip(self.mesh_data["node_ix"], self.mesh_data["node_iz"])
        ):
            for neighbor, coefficient in axis_derivative_entries(
                self.grid["x_axis"], int(ix)
            ):
                rows_theta.append(row)
                cols_theta.append(int(grid_to_film[neighbor, iz]))
                data_theta.append(coefficient)
            for neighbor, coefficient in axis_derivative_entries(
                self.grid["z_axis"], int(iz)
            ):
                rows_zeta.append(row)
                cols_zeta.append(int(grid_to_film[ix, neighbor]))
                data_zeta.append(coefficient)
        shape = (self.n, self.n)
        return (
            sp.csr_matrix((data_theta, (rows_theta, cols_theta)), shape=shape),
            sp.csr_matrix((data_zeta, (rows_zeta, cols_zeta)), shape=shape),
        )

    def _build_force_operator(self):
        """Build the exact pressure-to-global-force integration matrix."""

        operator = np.zeros((2, self.n), dtype=float)
        for element in self.model.elems.values():
            weight = float(element.lx * element.lz) / len(element.mapping)
            theta = float(element.mean_coords()[0])
            direction = np.array([np.sin(theta), -np.cos(theta)])
            for node_number in element.mapping:
                operator[:, int(node_number)] += weight * direction
        return operator

    def _set_fields(self, z, inputs):
        """Apply a state and input pair without invoking a nonlinear solve."""

        pressure, temperature, _ = self._split(z)
        inputs = np.asarray(inputs, dtype=float)
        # The analytic state uses normalized coordinates; the owned production
        # pad consumes SI inputs. Apply raw fields without advancing its lifecycle.
        args = self.model.args
        clearance = float(args["c"])
        velocity_scale = clearance * float(args["w_rad"]) * float(args["vf"])
        self.bearing._prepare_raw(BearingInput(
            inputs[:2] * clearance, inputs[2:4] * velocity_scale,
            0.0, UnitSystem.DIMENSIONAL,
        ))
        self.orifice.input(float(inputs[4 + self.spool_index]))
        self.orifice.model = self.model
        for index, node in enumerate(self.model.nodes.values()):
            node.p = float(pressure[index])

        miu_dim, _, _ = (
            self.thermal_model._nondim_viscosity_from_temperature_with_derivative(
                temperature, self.scales
            )
        )
        miu_film = np.asarray(miu_dim, dtype=float)[self.film_to_thermal]
        self.wrapper._apply_miu_ratio_to_nodes(miu_film)
        h_film = np.asarray(
            [node.h for node in self.model.nodes.values()], dtype=float
        )
        self.mesh_data["h_nodal"] = h_film[self.thermal_to_film]
        self.orifice.h = np.asarray(self.pressure_projection @ h_film).reshape(-1)
        self.orifice._calc_cq()
        return h_film

    def _thermal_context(self, z):
        """Return all nodal energy-equation fields and analytic coefficients."""

        pressure, temperature, _ = self._split(z)
        h_film = np.asarray(
            [node.h for node in self.model.nodes.values()], dtype=float
        )
        h = h_film[self.thermal_to_film]
        _, miu, dmiu_dt = (
            self.thermal_model._nondim_viscosity_from_temperature_with_derivative(
                temperature, self.scales
            )
        )
        miu = np.asarray(miu, dtype=float)
        dmiu_dt = np.asarray(dmiu_dt, dtype=float)
        pressure_theta = np.asarray(self.gradient_theta @ pressure).reshape(-1)
        pressure_zeta = np.asarray(self.gradient_zeta @ pressure).reshape(-1)
        a = h**3 / miu
        lr = float(self.scales.lr)
        lambda0 = float(self.scales.lambda0)
        theta_e = float(self.scales.theta_e)
        shear = lambda0**2 / (3.0 * lr**2)
        grad_sq = lr**2 * pressure_theta**2 + pressure_zeta**2
        qx = lambda0 * h - lr**2 * a * pressure_theta
        qz = -a * pressure_zeta
        phi = theta_e * (shear * miu / h + a * grad_sq)
        diff_x, diff_z = self.thermal_model._nondim_diffusion_coefficients(
            h, self.scales
        )

        da_dt = -(h**3 / miu**2) * dmiu_dt
        qx_dt = -lr**2 * pressure_theta * da_dt
        qz_dt = -pressure_zeta * da_dt
        phi_dt = theta_e * (
            shear * dmiu_dt / h + da_dt * grad_sq
        )

        da_dh = 3.0 * h**2 / miu
        qx_dh = lambda0 - lr**2 * pressure_theta * da_dh
        qz_dh = -pressure_zeta * da_dh
        phi_dh = theta_e * (
            -shear * miu / h**2 + da_dh * grad_sq
        )
        diff_x_dh = np.divide(
            diff_x,
            h,
            out=np.zeros_like(diff_x),
            where=np.abs(h) > 1.0e-30,
        )
        diff_z_dh = np.divide(
            diff_z,
            h,
            out=np.zeros_like(diff_z),
            where=np.abs(h) > 1.0e-30,
        )
        return {
            "pressure": pressure,
            "temperature": temperature,
            "h_film": h_film,
            "h": h,
            "miu": miu,
            "dmiu_dt": dmiu_dt,
            "pressure_theta": pressure_theta,
            "pressure_zeta": pressure_zeta,
            "a": a,
            "qx": qx,
            "qz": qz,
            "phi": phi,
            "diff_x": np.asarray(diff_x, dtype=float),
            "diff_z": np.asarray(diff_z, dtype=float),
            "qx_dt": qx_dt,
            "qz_dt": qz_dt,
            "phi_dt": phi_dt,
            "qx_dh": qx_dh,
            "qz_dh": qz_dh,
            "phi_dh": phi_dh,
            "diff_x_dh": diff_x_dh,
            "diff_z_dh": diff_z_dh,
        }

    def _thermal_boundary(self, qz):
        """Freeze the analytic thermal boundary branch at the base state."""

        tx = self.mesh.p[0]
        tz = self.mesh.p[1]
        x_min, x_max = float(tx.min()), float(tx.max())
        z_min, z_max = float(tz.min()), float(tz.max())
        inlet = np.where(np.abs(tx - x_min) < (x_max - x_min) * 1.0e-8)[0]
        side_min = np.where(np.abs(tz - z_min) < (z_max - z_min) * 1.0e-8)[0]
        side_max = np.where(np.abs(tz - z_max) < (z_max - z_min) * 1.0e-8)[0]
        parts = [inlet]
        mode = str(self.wrapper.config.axial_side_bc).lower()
        if mode == "fixed":
            parts.extend([side_min, side_max])
        elif mode == "inflow_fixed":
            if side_min.size and float(np.mean(qz[side_min])) > 0.0:
                parts.append(side_min)
            if side_max.size and float(np.mean(qz[side_max])) < 0.0:
                parts.append(side_max)
        elif mode != "adiabatic":
            raise ValueError(f"Unsupported thermal boundary mode: {mode}")
        nodes = np.unique(np.concatenate(parts)).astype(int)

        t_supply = (
            self.wrapper.config.t_supply
            if self.wrapper.config.t_supply is not None
            else self.wrapper.config.t_in
        )
        side_temperature = (
            self.wrapper.config.axial_side_t
            if self.wrapper.config.axial_side_t is not None
            else t_supply
        )
        side_bar = self.scales.temperature_to_nondim(
            side_temperature, t_supply
        )
        values = np.full(self.n, side_bar, dtype=float)
        values[inlet] = 0.0
        return nodes, values

    def _cold_source_nodes(self):
        """Return the thermal mesh node attached to each orifice source."""

        tx = self.mesh.p[0]
        tz = self.mesh.p[1]
        result = []
        # flow_info publishes actual film coordinates, including the pad angle.
        # Local [0, 1] configuration positions are not thermal mesh coordinates.
        for item in self.orifice.flow_info(self.model)["flow_params"]:
            position = item["position_nondim"]
            distance = (tx - float(position[0])) ** 2 + (
                tz - float(position[1])
            ) ** 2
            result.append(int(np.argmin(distance)))
        return np.asarray(result, dtype=int)

    def _pressure_residual_and_blocks(self, z, context):
        """Assemble the Reynolds residual and analytic state blocks."""

        pressure, _, orifice_state = self._split(z)
        h_film = context["h_film"]
        miu_ratio_film = np.asarray(
            [node.miu_ratio for node in self.model.nodes.values()], dtype=float
        )
        h_qp = self.pressure_basis.interpolate(h_film)
        miu_qp = self.pressure_basis.interpolate(miu_ratio_film)
        h3_over_miu = h_qp**3 / np.clip(miu_qp, 1.0e-12, None)
        theta = np.asarray(
            [node.coords[0] for node in self.model.nodes.values()], dtype=float
        )
        dh_dt = (
            float(self.model.args["xct"]) * np.sin(theta)
            - float(self.model.args["yct"]) * np.cos(theta)
        )
        j_pp = asm(
            _reynolds_lhs_miu,
            self.pressure_basis,
            h3_over_miu=h3_over_miu,
            lr=float(self.model.args["lr"]),
        ).tocsr()
        rhs = asm(
            _reynolds_rhs_miu0,
            self.pressure_basis,
            h=h_qp,
            dh_dt=self.pressure_basis.interpolate(dh_dt),
            lambda0=float(self.model.args["lambda0"]),
            vf=float(self.model.args["vf"]),
        )
        residual = np.asarray(j_pp @ pressure - rhs, dtype=float)
        residual -= np.asarray(self.pressure_projection.T @ orifice_state[2:]).reshape(-1)

        coeff = -h_qp**3 / np.clip(miu_qp, 1.0e-12, None) ** 2
        b_p_miu = asm(
            pressure_miu_block,
            self.pressure_basis,
            coeff=coeff,
            pressure0=self.pressure_basis.interpolate(pressure),
            lr=float(self.model.args["lr"]),
        ).tocsr()
        j_p_t = (
            b_p_miu
            @ self.map_film_from_thermal
            @ sp.diags(context["dmiu_dt"], format="csr")
        ).tocsr()
        j_p_y = sp.hstack([
            sp.csr_matrix((self.n, 2)), -self.pressure_projection.T,
        ], format="csr")
        return residual, j_pp, j_p_t, j_p_y

    def _thermal_residual_and_blocks(self, z, context):
        """Assemble the energy residual and all analytic state blocks."""

        pressure, temperature, orifice_state = self._split(z)
        basis = self.thermal_basis
        interp = basis.interpolate
        common = {
            "qx": interp(context["qx"]),
            "qz": interp(context["qz"]),
            "phi": interp(context["phi"]),
            "tau": interp(self.tau),
            "temperature0": interp(temperature),
        }
        a_direct = asm(
            thermal_direct_block,
            basis,
            qx=common["qx"],
            qz=common["qz"],
            tau=common["tau"],
            diff_x=interp(context["diff_x"]),
            diff_z=interp(context["diff_z"]),
        ).tolil()
        source = asm(
            thermal_source_vector,
            basis,
            qx=common["qx"],
            qz=common["qz"],
            phi=common["phi"],
            tau=common["tau"],
        )
        if self.orifice.flow_projection == "element_shape":
            source_flows = orifice_state[2:] * self.cold_source_active
            a_direct = a_direct + (
                self.thermal_projection.T @ sp.diags(source_flows)
                @ self.thermal_projection
            )
        else:
            for index, node_number in enumerate(self.cold_source_nodes):
                if self.cold_source_active[index]:
                    a_direct[int(node_number), int(node_number)] += float(
                        orifice_state[2 + index]
                    )
        a_direct = a_direct.tocsr()
        residual = np.asarray(a_direct @ temperature - source, dtype=float)

        block_kwargs = {
            "temperature0": common["temperature0"],
            "qx": common["qx"],
            "qz": common["qz"],
            "phi": common["phi"],
            "tau": common["tau"],
        }
        b_qx = asm(thermal_qx_coefficient_block, basis, **block_kwargs).tocsr()
        b_qz = asm(thermal_qz_coefficient_block, basis, **block_kwargs).tocsr()
        b_phi = asm(
            thermal_phi_coefficient_block,
            basis,
            qx=common["qx"],
            qz=common["qz"],
            tau=common["tau"],
        ).tocsr()
        b_diff_x = asm(
            thermal_diff_x_coefficient_block,
            basis,
            temperature0=common["temperature0"],
        ).tocsr()
        b_diff_z = asm(
            thermal_diff_z_coefficient_block,
            basis,
            temperature0=common["temperature0"],
        ).tocsr()

        j_t_t = (
            a_direct
            + b_qx @ sp.diags(context["qx_dt"], format="csr")
            + b_qz @ sp.diags(context["qz_dt"], format="csr")
            + b_phi @ sp.diags(context["phi_dt"], format="csr")
        ).tocsr()

        lr = float(self.scales.lr)
        qx_p = -sp.diags(lr**2 * context["a"]) @ self.gradient_theta
        qz_p = -sp.diags(context["a"]) @ self.gradient_zeta
        phi_p = (
            sp.diags(
                2.0
                * float(self.scales.theta_e)
                * context["a"]
                * lr**2
                * context["pressure_theta"]
            )
            @ self.gradient_theta
            + sp.diags(
                2.0
                * float(self.scales.theta_e)
                * context["a"]
                * context["pressure_zeta"]
            )
            @ self.gradient_zeta
        )
        j_t_p = (b_qx @ qx_p + b_qz @ qz_p + b_phi @ phi_p).tocsr()

        geometry_operator_thermal = (
            b_diff_x @ sp.diags(context["diff_x_dh"])
            + b_diff_z @ sp.diags(context["diff_z_dh"])
            + b_qx @ sp.diags(context["qx_dh"])
            + b_qz @ sp.diags(context["qz_dh"])
            + b_phi @ sp.diags(context["phi_dh"])
        ).tocsr()

        source_temperature = np.asarray(self.thermal_projection @ temperature)
        j_t_y = sp.hstack([
            sp.csr_matrix((self.n, 2)),
            self.thermal_projection.T
            @ sp.diags(source_temperature * self.cold_source_active),
        ], format="csr")
        return (
            residual,
            j_t_p,
            j_t_t,
            j_t_y.tocsr(),
            geometry_operator_thermal,
        )

    def _orifice_residual_and_blocks(self, z, context):
        """Assemble the capillary-slot residual and analytic state blocks."""

        pressure, _, y = self._split(z)
        qs, psv = y[:2]
        q_nodes = y[2:]
        pn = np.asarray(self.pressure_projection @ pressure).reshape(-1)
        supply = float(self.orifice._supply_pressure_for_equations())
        leakage = float(self.orifice._leakage_flow_for_equations())
        spool_signed = float(self.orifice.xv)
        spool = abs(spool_signed)
        delta_supply = supply - psv
        sigma = 1.0 if delta_supply >= 0.0 else -1.0
        root = np.sqrt(abs(delta_supply))
        valve_flow = sigma * (
            leakage + float(self.orifice.cq0) * spool * root
        )
        residual = np.empty(5, dtype=float)
        residual[0] = qs - np.sum(q_nodes)
        residual[1] = qs - valve_flow
        residual[2:] = (
            np.asarray(self.orifice.cq1_h2, dtype=float)
            * q_nodes
            * np.abs(q_nodes)
            + float(self.orifice.cq2) * q_nodes
            - (psv - pn)
        )

        j_y_p = sp.lil_matrix((5, self.n), dtype=float)
        j_y_p[2:, :] = self.pressure_projection
        j_y_y = sp.lil_matrix((5, 5), dtype=float)
        j_y_y[0, 0] = 1.0
        j_y_y[0, 2:] = -1.0
        j_y_y[1, 0] = 1.0
        j_y_y[1, 1] = (
            float(self.orifice.cq0)
            * spool
            / (2.0 * max(root, 1.0e-14))
        )
        for index, node_number in enumerate(self.of_nodes):
            row = 2 + index
            j_y_y[row, 1] = -1.0
            j_y_y[row, row] = (
                2.0
                * float(self.orifice.cq1_h2[index])
                * abs(float(q_nodes[index]))
                + float(self.orifice.cq2)
            )
        geometry_coeff = np.zeros((5, 3), dtype=float)
        geometry_coeff[2:, :] = np.diag(
            -2.0
            * float(self.orifice.cq1)
            * q_nodes
            * np.abs(q_nodes)
            / np.asarray(self.pressure_projection @ context["h_film"]) ** 3
        )
        spool_coefficient = (
            -sigma
            * float(self.orifice.cq0)
            * np.sign(spool_signed)
            * root
        )
        return (
            residual,
            j_y_p.tocsr(),
            j_y_y.tocsr(),
            geometry_coeff,
            spool_coefficient,
        )

    def assemble(self, z=None):
        """Assemble the full nonlinear residual and exact analytic Jacobian."""

        if z is None:
            z = self.z
        z = np.asarray(z, dtype=float)
        self._set_fields(z, self.base_input)
        context = self._thermal_context(z)
        r_p, j_pp, j_pt, j_py = self._pressure_residual_and_blocks(z, context)
        r_t, j_tp, j_tt, j_ty, geometry_t = self._thermal_residual_and_blocks(
            z, context
        )
        r_y, j_yp, j_yy, geometry_y, spool_y = (
            self._orifice_residual_and_blocks(z, context)
        )
        zero_y_t = sp.csr_matrix((5, self.n), dtype=float)
        jacobian = sp.bmat(
            [
                [j_pp, j_pt, j_py],
                [j_tp, j_tt, j_ty],
                [j_yp, zero_y_t, j_yy],
            ],
            format="lil",
        )
        residual = np.r_[r_p, r_t, r_y]

        constrained_rows = list(np.where(~self.active_pressure)[0]) + [
            self.n + int(row) for row in self.dirichlet_nodes
        ]
        pressure, temperature, _ = self._split(z)
        for row in np.where(~self.active_pressure)[0]:
            residual[int(row)] = pressure[int(row)]
        for row in self.dirichlet_nodes:
            residual[self.n + int(row)] = (
                temperature[int(row)] - self.temperature_bc[int(row)]
            )
        for row in constrained_rows:
            jacobian.rows[int(row)] = [int(row)]
            jacobian.data[int(row)] = [1.0]

        context.update(
            {
                "geometry_t": geometry_t,
                "geometry_y": geometry_y,
                "spool_y": spool_y,
            }
        )
        self.last_context = context
        return residual, jacobian.tocsc(), context

    def analytic_input_column(self, input_index, context):
        """Return the exact residual derivative for one independent input."""

        theta = np.asarray(
            [node.coords[0] for node in self.model.nodes.values()], dtype=float
        )
        dh_film = np.zeros(self.n, dtype=float)
        dh_dt = np.zeros(self.n, dtype=float)
        if input_index == 0:
            dh_film = np.sin(theta)
        elif input_index == 1:
            dh_film = -np.cos(theta)
        elif input_index == 2:
            dh_dt = np.sin(theta)
        elif input_index == 3:
            dh_dt = -np.cos(theta)

        h_qp = self.pressure_basis.interpolate(context["h_film"])
        miu_ratio = np.asarray(
            [node.miu_ratio for node in self.model.nodes.values()], dtype=float
        )
        miu_qp = self.pressure_basis.interpolate(miu_ratio)
        pressure_column = asm(
            pressure_geometry_column,
            self.pressure_basis,
            da_dh=3.0 * h_qp**2 / np.clip(miu_qp, 1.0e-12, None),
            dh=self.pressure_basis.interpolate(dh_film),
            dh_dt=self.pressure_basis.interpolate(dh_dt),
            pressure0=self.pressure_basis.interpolate(context["pressure"]),
            lr=float(self.model.args["lr"]),
            lambda0=float(self.model.args["lambda0"]),
            vf=float(self.model.args["vf"]),
        )
        dh_thermal = np.asarray(
            self.map_thermal_from_film @ dh_film
        ).reshape(-1)
        thermal_column = np.asarray(
            context["geometry_t"] @ dh_thermal
        ).reshape(-1)
        orifice_column = np.asarray(
            context["geometry_y"] @ (self.pressure_projection @ dh_film)
        ).reshape(-1)
        if input_index == 4 + self.spool_index:
            orifice_column[1] += float(context["spool_y"])

        pressure_column[~self.active_pressure] = 0.0
        thermal_column[self.dirichlet_nodes] = 0.0
        return np.r_[pressure_column, thermal_column, orifice_column]
